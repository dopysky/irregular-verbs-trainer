const assert = require('node:assert/strict');
const {createAccountStorage} = require('./account-storage');
(async () => {
  const calls = [], snapshots = {legacy:{theme:'dark'},grammar:{results:{x:1}}};
  const engine = {load:async section=>snapshots[section],set:(section,data)=>{calls.push([section,data]);snapshots[section]=data;},flush:async section=>calls.push(['flush',section])};
  const bridge=await createAccountStorage(engine,{schedule:fn=>fn()});
  assert.equal(JSON.parse(bridge.get('legacy')).theme,'dark');
  bridge.set('grammar',JSON.stringify({results:{x:2}}));
  await new Promise(resolve=>setImmediate(resolve));
  assert.deepEqual(calls,[['grammar',{results:{x:2}}],['flush','grammar']]);
  assert.throws(()=>bridge.set('legacy','not JSON'));
  const pending=new Set(), statuses=[];
  let resolveLegacy;
  const slow={load:async()=>null,set:s=>pending.add(s),pending:s=>pending.has(s),flush:async s=>{if(s==='legacy')await new Promise(r=>resolveLegacy=r);pending.delete(s);}};
  const delayed=await createAccountStorage(slow,{schedule:fn=>fn(),onStatus:s=>statuses.push(s)});
  delayed.set('legacy','{"a":1}');delayed.set('grammar','{"b":1}');
  await new Promise(resolve=>setImmediate(resolve));
  assert.notEqual(statuses.at(-1),'saved','must not report saved while another section remains pending');
  resolveLegacy();await new Promise(resolve=>setImmediate(resolve));
  assert.equal(statuses.at(-1),'saved');
  const warnings=[];
  const changed={load:async()=>null,set:()=>{throw Object.assign(new Error('changed'),{code:'CONFLICT'});},flush:async()=>{}};
  const changedBridge=await createAccountStorage(changed,{onStatus:s=>warnings.push(s)});
  assert.throws(()=>changedBridge.set('legacy','{"a":1}'),/changed/);
  assert.equal(warnings.at(-1),'local-conflict');
  let localRecovered=0;changed.recoverFromCloud=async()=>{localRecovered++;};await changedBridge.recoverFromCloud();assert.equal(localRecovered,1,'a conflict between tabs must offer recovery too');
  const issues=[], pendingRecovery=new Set(); let restored=0;
  const recoveryEngine={load:async()=>({old:true}),set:s=>pendingRecovery.add(s),pending:s=>pendingRecovery.has(s),flush:async()=>{throw Object.assign(Error('conflict'),{code:'CONFLICT'});},recoverFromCloud:async s=>{restored++;pendingRecovery.delete(s);}};
  const recovery=await createAccountStorage(recoveryEngine,{schedule:fn=>fn(),onStatus:s=>issues.push(s)});
  recovery.set('grammar','{"old":true}');await new Promise(r=>setImmediate(r));assert.equal(issues.at(-1),'conflict');
  await recovery.recoverFromCloud();assert.equal(restored,1);assert.equal(issues.at(-1),'saved');
  console.log('Account storage reads account data and queues progress updates.');
})().catch(error=>{console.error(error);process.exitCode=1;});
