const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const ctx = {window:{TRAINING_TOPICS:[]}};
vm.runInNewContext(fs.readFileSync('present-continuous-now.js','utf8'), ctx);
const topic = ctx.window.TRAINING_TOPICS.find(t => t.id === 'present-continuous-now');
assert(topic);
assert.equal(topic.cards.length, 1);
assert.equal(topic.exercises.length, 3);
assert.deepEqual(Array.from(topic.exercises, q => q.mode), ['choice','gap','full']);
const {task,accepts} = require('./topics-core.js');
const [choice,gap,full] = topic.exercises.map(q => task(q));
assert(accepts(choice,'is sleeping'));
assert(!accepts(choice,'are sleeping') && !accepts(choice,'is sleep'));
assert(topic.exercises[0].choice_feedback['are sleeping']);
assert(topic.exercises[0].choice_feedback['is sleep']);
assert(accepts(gap,'AM.'));
assert(accepts(full,'THEY ARE PLAYING NOW!'));
assert(accepts(full,"They're playing now."));
assert(!accepts(full,'They is playing now'));
for (const q of topic.exercises) assert(q.feedback_explanation);
for (const q of topic.exercises) assert(q.explain_skip, 'Объяснение должно показываться после «Не знаю»');
assert(fs.readFileSync('topics.js','utf8').includes('skipped&&!q.source.explain_skip'));
assert(fs.existsSync(topic.cards[0].figures[0].src));
console.log('Present Continuous: ответы и состав проверены');
